/**
 * Renders a list of contact items with an icon and a link.
 * Uses metadata.url as href and metadata.icon to select the inline SVG icon.
 */
export function ContactList({ sections }: ContactListProps) {
  if (sections.length === 0) return null;

  return (
    <section aria-labelledby="contact-heading" className="mb-10">
      <h2 id="contact-heading" className="text-2xl font-semibold text-foreground mb-6">
        Kontak
      </h2>

      <ul className="space-y-3" data-testid="contact-list">
        {sections.map((section) => {
          const url = section.metadata?.url;
          const icon = section.metadata?.icon;

          return (
            <li key={section.id} className="flex items-center gap-3">
              <span className="text-muted-foreground shrink-0">
                <ContactIcon icon={icon} />
              </span>

              {url ? (
                <a
                  href={url}
                  target="_blank"
                  rel="noopener noreferrer"
                  className="text-primary hover:underline underline-offset-2 text-sm"
                >
                  {section.title}
                </a>
              ) : (
                <span className="text-sm text-foreground">{section.title}</span>
              )}

              {section.subtitle && (
                <span className="text-sm text-muted-foreground">· {section.subtitle}</span>
              )}
            </li>
          );
        })}
      </ul>
    </section>
  );
}
