// Feature: personal-blog-website, Property 3: Published post auto-reverts to Draft on edit
// ─────────────────────────────────────────────────────────────────────────────

describe('Property 3: Published post auto-reverts to Draft on edit', () => {
  beforeEach(() => {
    vi.clearAllMocks();
    vi.mocked(prisma.comment.count).mockResolvedValue(0 as never);
    vi.mocked(prisma.comment.groupBy).mockResolvedValue([] as never);
    vi.mocked(prisma.postTag.findMany).mockResolvedValue([] as never);
  });

  /**
   * **Validates: Requirements 3.4**
   *
   * For any Published post that receives any update (title, content, or both),
   * `updatePost()` MUST return a post whose status is `"draft"`, regardless of
   * the specific field(s) being edited.
   */
  it(
    'always returns status "draft" after editing a Published post, for any combination of title/content changes',
    async () => {
      await fc.assert(
        fc.asyncProperty(
          // Original title of the published post
          titleArb,
          // Optional new title (undefined means only content is changed)
          fc.option(titleArb, { nil: undefined }),
          // Optional new content (undefined means only title is changed)
          fc.option(fc.string({ minLength: 1, maxLength: 200 }), { nil: undefined }),
          async (originalTitle, newTitle, newContent) => {
            // At least one field must be provided for the update to be meaningful
            fc.pre(newTitle !== undefined || newContent !== undefined);

            // If a new title is given, it may equal the original (still triggers an update path)
            const originalSlug = baseSlug(originalTitle);
            fc.pre(originalSlug.length > 0);

            const postId = 'test-post-id';
            const publishedAt = new Date();
            const now = new Date();

            // --- Prisma mock setup ---

            vi.mocked(prisma.post.findUnique).mockImplementation(
              ({ where }: { where: { id?: string; slug?: string } }) => {
                if (where.id !== undefined) {
                  // `updatePost` loads the existing post
                  return Promise.resolve({
                    id: postId,
                    title: originalTitle,
                    slug: originalSlug,
                    content: 'original content',
                    status: 'published',        // ← the post is Published
                    publishedAt,
                    createdAt: now,
                    updatedAt: now,
                    _count: { comments: 0 },
                  }) as never;
                }
                // `generateUniqueSlug` slug-availability check — no collision
                return Promise.resolve(null) as never;
              },
            );

            vi.mocked(prisma.post.findMany).mockResolvedValue([] as never);

            // `prisma.post.update` echoes back whatever data was written so that
            // `mapPost` can build the returned Post object correctly.
            vi.mocked(prisma.post.update).mockImplementation(
              ({ data }: { data: { title?: string; slug?: string; content?: string; status?: string; publishedAt?: Date | null } }) => {
                return Promise.resolve({
                  id: postId,
                  title: (data.title as string) ?? originalTitle,
                  slug: (data.slug as string) ?? originalSlug,
                  content: (data.content as string) ?? 'original content',
                  status: (data.status as string) ?? 'published',
                  publishedAt: data.publishedAt !== undefined ? data.publishedAt : publishedAt,
                  createdAt: now,
                  updatedAt: new Date(),
                  _count: { comments: 0 },
                }) as never;
              },
            );

            // --- Execute ---

            const updates: { title?: string; content?: string } = {};
            if (newTitle !== undefined) updates.title = newTitle;
            if (newContent !== undefined) updates.content = newContent;

            const result = await updatePost(postId, updates);

            // --- Core property: status MUST be "draft" ----------------------
            expect(result.status).toBe('draft');
          },
        ),
        { numRuns: 100 },
      );
    },
  );

  /**
   * **Validates: Requirements 3.4**
   *
   * Editing a post that is already in Draft status must NOT change the status
   * (it stays "draft" — no unintended side-effects from the revert logic).
   */
  it(
    'keeps status "draft" when editing a post that is already Draft',
    async () => {
      await fc.assert(
        fc.asyncProperty(
          titleArb,
          fc.string({ minLength: 1, maxLength: 200 }),
          async (originalTitle, newContent) => {
            const originalSlug = baseSlug(originalTitle);
            fc.pre(originalSlug.length > 0);

            const postId = 'test-post-id';
            const now = new Date();

            vi.mocked(prisma.post.findUnique).mockImplementation(
              ({ where }: { where: { id?: string; slug?: string } }) => {
                if (where.id !== undefined) {
                  return Promise.resolve({
                    id: postId,
                    title: originalTitle,
                    slug: originalSlug,
                    content: 'original content',
                    status: 'draft',            // ← already Draft
                    publishedAt: null,
                    createdAt: now,
                    updatedAt: now,
                    _count: { comments: 0 },
                  }) as never;
                }
                return Promise.resolve(null) as never;
              },
            );

            vi.mocked(prisma.post.findMany).mockResolvedValue([] as never);

            vi.mocked(prisma.post.update).mockImplementation(
              ({ data }: { data: { content?: string; status?: string } }) => {
                return Promise.resolve({
                  id: postId,
                  title: originalTitle,
                  slug: originalSlug,
                  content: (data.content as string) ?? 'original content',
                  status: (data.status as string) ?? 'draft',
                  publishedAt: null,
                  createdAt: now,
                  updatedAt: new Date(),
                  _count: { comments: 0 },
                }) as never;
              },
            );

            const result = await updatePost(postId, { content: newContent });

            // A Draft post stays Draft after an edit — no status change
            expect(result.status).toBe('draft');
          },
        ),
        { numRuns: 100 },
      );
    },
  );
});
