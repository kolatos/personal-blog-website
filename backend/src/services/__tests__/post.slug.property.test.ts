// Feature: personal-blog-website, Property 1: Slug uniqueness after generation

import { describe, it, expect, vi, beforeEach } from 'vitest';
import * as fc from 'fast-check';

// ── Module mocks (hoisted before real imports) ────────────────────────────────
// Prisma must be mocked so the test is a pure unit test — no real DB needed.

vi.mock('../../lib/prisma', () => ({
  default: {
    post: {
      findUnique: vi.fn(),
      findMany: vi.fn(),
      update: vi.fn(),
    },
    comment: {
      count: vi.fn().mockResolvedValue(0),
      groupBy: vi.fn().mockResolvedValue([]),
      deleteMany: vi.fn().mockResolvedValue({ count: 0 }),
    },
    postTag: {
      findMany: vi.fn().mockResolvedValue([]),
    },
  },
}));

// marked is used inside mapPost/mapPostSummary; not needed here but the module
// is imported transitively — mock it to avoid ESM/native issues in tests.
vi.mock('marked', () => ({
  marked: vi.fn().mockResolvedValue('<p>content</p>'),
}));

import prisma from '../../lib/prisma';
import { generateUniqueSlug, updatePost } from '../post.service';

// ── Helpers ───────────────────────────────────────────────────────────────────

/**
 * Derives the base slug for a title the same way `generateUniqueSlug` does,
 * so we can construct expected collision values without coupling to the impl.
 */
import slugify from 'slugify';

function baseSlug(title: string): string {
  return slugify(title, { lower: true, strict: true, trim: true });
}

/**
 * Builds the minimal Prisma mock state for a list of already-persisted titles.
 *
 * `findUnique({ where: { slug } })` returns a record when `slug` is in the
 * existing set, and null otherwise.
 *
 * `findMany({ where: { slug: { startsWith: prefix } } })` returns all records
 * whose slug starts with `prefix`.
 */
function setupPrismaMock(existingSlugs: string[]): void {
  const slugSet = new Set(existingSlugs);

  vi.mocked(prisma.post.findUnique).mockImplementation(({ where }: { where: { slug?: string; id?: string } }) => {
    const slug = where.slug;
    if (slug === undefined) return Promise.resolve(null) as never;
    return Promise.resolve(slugSet.has(slug) ? { id: 'existing-id', slug } : null) as never;
  });

  vi.mocked(prisma.post.findMany).mockImplementation(
    ({ where }: { where: { slug: { startsWith: string } } }) => {
      const prefix = where?.slug?.startsWith;
      if (!prefix) return Promise.resolve([]) as never;
      const matches = existingSlugs
        .filter((s) => s.startsWith(prefix))
        .map((s) => ({ slug: s }));
      return Promise.resolve(matches) as never;
    },
  );
}

// ── Arbitraries ───────────────────────────────────────────────────────────────

/**
 * Generates post titles: non-empty strings of printable ASCII letters/spaces.
 * We constrain to characters that slugify will not strip entirely, so the
 * resulting base slug is always non-empty.
 */
const titleArb = fc
  .stringOf(
    fc.mapToConstant(
      { num: 26, build: (n) => String.fromCharCode(65 + n) }, // A-Z
      { num: 26, build: (n) => String.fromCharCode(97 + n) }, // a-z
      { num: 10, build: (n) => String.fromCharCode(48 + n) }, // 0-9
      { num: 1, build: () => ' ' },
    ),
    { minLength: 1, maxLength: 40 },
  )
  // Ensure at least one alphanumeric so slugify yields a non-empty result
  .filter((s) => /[a-zA-Z0-9]/.test(s));

/**
 * Generates a set of 0–9 existing titles to seed the "database".
 */
const existingTitlesArb = fc.array(titleArb, { minLength: 0, maxLength: 9 });

// ── Tests ─────────────────────────────────────────────────────────────────────

describe('Property 1: Slug uniqueness after generation', () => {
  beforeEach(() => {
    vi.clearAllMocks();
  });

  /**
   * **Validates: Requirements 3.1, 3.2**
   *
   * For any set of posts already in the database and any new post title,
   * the slug generated by `generateUniqueSlug` MUST NOT collide with any
   * slug that already exists in the database.
   */
  it(
    'never collides with any existing slug regardless of title set or new title',
    async () => {
      await fc.assert(
        fc.asyncProperty(
          existingTitlesArb,
          titleArb,
          async (existingTitles, newTitle) => {
            // Derive the set of slugs that would be persisted for existing titles.
            // We simulate the slug-assignment process sequentially so each title
            // gets the correct suffix-aware slug, just like real creation would.
            const persistedSlugs: string[] = [];
            for (const title of existingTitles) {
              setupPrismaMock(persistedSlugs);
              const slug = await generateUniqueSlug(title);
              persistedSlugs.push(slug);
            }

            // Now generate a slug for the new title against the full existing set.
            setupPrismaMock(persistedSlugs);
            const newSlug = await generateUniqueSlug(newTitle);

            // The core property: the new slug must not match any existing slug.
            expect(persistedSlugs).not.toContain(newSlug);
          },
        ),
        { numRuns: 100 },
      );
    },
  );

  /**
   * **Validates: Requirements 3.1, 3.2**
   *
   * When the base slug is already taken, the function appends a numeric suffix
   * (-2, -3, …) so the result is still unique.
   */
  it(
    'appends a numeric suffix when the base slug already exists',
    async () => {
      await fc.assert(
        fc.asyncProperty(titleArb, async (title) => {
          const base = baseSlug(title);
          if (!base) return; // guard: slugify returned empty string

          // Seed: the base slug is already taken.
          setupPrismaMock([base]);

          const result = await generateUniqueSlug(title);

          // Must differ from the base slug.
          expect(result).not.toBe(base);

          // Must start with the base slug followed by a dash and a number >= 2.
          expect(result).toMatch(new RegExp(`^${base.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}-\\d+$`));
          const suffix = parseInt(result.slice(base.length + 1), 10);
          expect(suffix).toBeGreaterThanOrEqual(2);
        }),
        { numRuns: 100 },
      );
    },
  );

  /**
   * **Validates: Requirements 3.1, 3.2**
   *
   * When multiple collisions exist (base, base-2, base-3, …), the next suffix
   * is always max+1, ensuring no gaps are reused and no collision occurs.
   */
  it(
    'increments suffix beyond the highest existing numeric suffix on repeated collisions',
    async () => {
      await fc.assert(
        fc.asyncProperty(
          titleArb,
          fc.integer({ min: 1, max: 8 }),
          async (title, collisionCount) => {
            const base = baseSlug(title);
            if (!base) return;

            // Build a collision chain: base, base-2, base-3, … base-(collisionCount+1)
            const existingSlugs = [base];
            for (let i = 2; i <= collisionCount + 1; i++) {
              existingSlugs.push(`${base}-${i}`);
            }

            setupPrismaMock(existingSlugs);
            const result = await generateUniqueSlug(title);

            // Must not be any of the existing slugs
            expect(existingSlugs).not.toContain(result);

            // The new suffix must be collisionCount + 2 (next after the chain end)
            const expectedSuffix = collisionCount + 2;
            expect(result).toBe(`${base}-${expectedSuffix}`);
          },
        ),
        { numRuns: 100 },
      );
    },
  );

  /**
   * **Validates: Requirements 3.1**
   *
   * When no collisions exist, the slug equals the base slugified form exactly.
   */
  it(
    'returns the base slugified title when no collision exists',
    async () => {
      await fc.assert(
        fc.asyncProperty(titleArb, async (title) => {
          const base = baseSlug(title);
          if (!base) return;

          // No existing slugs — empty DB
          setupPrismaMock([]);

          const result = await generateUniqueSlug(title);

          expect(result).toBe(base);
        }),
        { numRuns: 100 },
      );
    },
  );
});

// ─────────────────────────────────────────────────────────────────────────────
// Feature: personal-blog-website, Property 2: Slug regeneration on title change
// ─────────────────────────────────────────────────────────────────────────────

describe('Property 2: Slug regeneration on title change', () => {
  beforeEach(() => {
    vi.clearAllMocks();
    vi.mocked(prisma.comment.count).mockResolvedValue(0 as never);
    vi.mocked(prisma.comment.groupBy).mockResolvedValue([] as never);
    vi.mocked(prisma.postTag.findMany).mockResolvedValue([] as never);
  });

  /**
   * **Validates: Requirements 3.3**
   *
   * For any existing post with a given slug and a new title that is different
   * from the original title, calling `updatePost()` MUST:
   *   1. Return a post whose slug is NOT the original slug.
   *   2. Return a post whose slug is derived from the new title (i.e. starts
   *      with the slugified form of the new title).
   */
  it(
    'generates a new slug derived from the new title when the title changes',
    async () => {
      await fc.assert(
        fc.asyncProperty(
          // Original title
          titleArb,
          // New title — must differ from the original
          titleArb,
          async (originalTitle, newTitle) => {
            // Ensure titles are actually different; skip if they happen to be equal
            fc.pre(originalTitle !== newTitle);

            const originalSlug = baseSlug(originalTitle);
            const newBaseSlug = baseSlug(newTitle);

            // Both base slugs must be non-empty after slugification
            fc.pre(originalSlug.length > 0 && newBaseSlug.length > 0);

            const postId = 'test-post-id';
            const now = new Date();

            // --- Prisma mock setup ---

            // `findUnique` is called twice inside `updatePost`:
            //   1. To load the existing post for the update logic.
            //   2. Inside `generateUniqueSlug` to check if the new base slug exists.
            //
            // We track call order via a simple counter.
            let findUniqueCallCount = 0;

            vi.mocked(prisma.post.findUnique).mockImplementation(
              ({ where }: { where: { id?: string; slug?: string } }) => {
                findUniqueCallCount += 1;

                if (where.id !== undefined) {
                  // Called by `updatePost` to load the existing post
                  return Promise.resolve({
                    id: postId,
                    title: originalTitle,
                    slug: originalSlug,
                    content: 'original content',
                    status: 'draft',
                    publishedAt: null,
                    createdAt: now,
                    updatedAt: now,
                    _count: { comments: 0 },
                  }) as never;
                }

                // Called by `generateUniqueSlug` — return null so the new base
                // slug is available (no collision), making the result predictable.
                return Promise.resolve(null) as never;
              },
            );

            // `findMany` is only called when there IS a collision; since we
            // mock `findUnique` to return null for slug lookups, it won't be
            // reached, but we stub it defensively.
            vi.mocked(prisma.post.findMany).mockResolvedValue([] as never);

            // `prisma.post.update` must reflect the new slug in its return value
            vi.mocked(prisma.post.update).mockImplementation(
              ({ data }: { data: { title?: string; slug?: string; content?: string; status?: string } }) => {
                const resolvedSlug = (data.slug as string) ?? originalSlug;
                return Promise.resolve({
                  id: postId,
                  title: (data.title as string) ?? originalTitle,
                  slug: resolvedSlug,
                  content: (data.content as string) ?? 'original content',
                  status: (data.status as string) ?? 'draft',
                  publishedAt: null,
                  createdAt: now,
                  updatedAt: new Date(),
                  _count: { comments: 0 },
                }) as never;
              },
            );

            // --- Execute ---

            const result = await updatePost(postId, { title: newTitle });

            // --- Assertions ---

            // 1. The new slug must differ from the original slug
            //    (unless the two titles happen to slugify identically — skip
            //     that degenerate case with fc.pre above for the base slugs)
            if (originalSlug !== newBaseSlug) {
              expect(result.slug).not.toBe(originalSlug);
            }

            // 2. The new slug must be derived from the new title:
            //    it should start with the slugified form of the new title.
            expect(result.slug).toMatch(
              new RegExp(`^${newBaseSlug.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}(-\\d+)?$`),
            );
          },
        ),
        { numRuns: 100 },
      );
    },
  );

  /**
   * **Validates: Requirements 3.3**
   *
   * When the title is NOT changed, `updatePost()` must preserve the original
   * slug unchanged (no unnecessary slug regeneration).
   */
  it(
    'preserves the original slug when the title is unchanged',
    async () => {
      await fc.assert(
        fc.asyncProperty(titleArb, async (title) => {
          const slug = baseSlug(title);
          fc.pre(slug.length > 0);

          const postId = 'test-post-id';
          const now = new Date();

          vi.mocked(prisma.post.findUnique).mockImplementation(
            ({ where }: { where: { id?: string; slug?: string } }) => {
              if (where.id !== undefined) {
                return Promise.resolve({
                  id: postId,
                  title,
                  slug,
                  content: 'some content',
                  status: 'draft',
                  publishedAt: null,
                  createdAt: now,
                  updatedAt: now,
                  _count: { comments: 0 },
                }) as never;
              }
              return Promise.resolve(null) as never;
            },
          );

          vi.mocked(prisma.post.findMany).mockResolvedValue([] as never);

          // Capture what slug `prisma.post.update` is called with
          let capturedSlug: string | undefined;

          vi.mocked(prisma.post.update).mockImplementation(
            ({ data }: { data: { title?: string; slug?: string; content?: string; status?: string } }) => {
              capturedSlug = data.slug as string | undefined;
              return Promise.resolve({
                id: postId,
                title,
                slug,
                content: (data.content as string) ?? 'some content',
                status: 'draft',
                publishedAt: null,
                createdAt: now,
                updatedAt: new Date(),
                _count: { comments: 0 },
              }) as never;
            },
          );

          // Update only the content, leaving the title untouched
          const result = await updatePost(postId, { content: 'updated content' });

          // The slug in the DB update call must NOT have been set
          // (meaning updatePost did not touch it)
          expect(capturedSlug).toBeUndefined();

          // And the returned slug must still match the original
          expect(result.slug).toBe(slug);
        }),
        { numRuns: 100 },
      );
    },
  );
});

